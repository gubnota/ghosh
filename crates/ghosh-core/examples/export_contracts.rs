use ghosh_core::{
    approvals::*,
    automation::*,
    contracts::*,
    operations::*,
    ssh::*,
    ssh_keys::*,
    terminal::*,
    workspace::{
        automation::*,
        identity::*,
        inventory::*,
        model::{Auth, AuthMethod, Manifest, Node},
    },
};
use std::{fs, path::PathBuf};
use ts_rs::TS;
fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let mut types = String::from("// Generated by ghosh-core export_contracts. Do not edit.\n");
    for declaration in [
        AutomationKind::decl(),
        AutomationDocument::decl(),
        AutomationValidation::decl(),
        AutomationSummary::decl(),
        AutomationReadRequest::decl(),
        AutomationMutation::decl(),
        AutomationPreview::decl(),
        AutomationCommit::decl(),
        ErrorCode::decl(),
        NodeConnectionRequest::decl(),
        HostTrust::decl(),
        HostKeyPreview::decl(),
        NodeConnectionPreview::decl(),
        NodeConnectionCommit::decl(),
        NodeTerminalRequest::decl(),
        NodeConnectionResult::decl(),
        TerminalSize::decl(),
        TerminalSession::decl(),
        TerminalPacket::decl(),
        AppError::decl(),
        NodeSummary::decl(),
        AuthMethod::decl(),
        Auth::decl(),
        Node::decl(),
        NodeChange::decl(),
        NodeMutationRequest::decl(),
        NodeCommitRequest::decl(),
        NodeChangePreview::decl(),
        WorkspaceSnapshot::decl(),
        RevisionRequest::decl(),
        RenameRequest::decl(),
        TrustRequest::decl(),
        CreateRequest::decl(),
        RecentWorkspace::decl(),
        KeyStorage::decl(),
        KeyStatus::decl(),
        PublicKeyMetadata::decl(),
        KeyImportRequest::decl(),
        KeyImportPreview::decl(),
        KeyCommitRequest::decl(),
        KeySummary::decl(),
        KeysSnapshot::decl(),
        KeyRegistryRequest::decl(),
        KeyGenerateRequest::decl(),
        KeyRelinkRequest::decl(),
        WorkspaceKeyRequest::decl(),
        WorkspaceKeyPreview::decl(),
        WorkspaceKeyCommit::decl(),
        IdentityPreview::decl(),
        NodeIdentityRequest::decl(),
        WorkspaceEvent::decl(),
        JobKind::decl(),
        JobState::decl(),
        JobStage::decl(),
        JobSnapshot::decl(),
        JobsSnapshot::decl(),
        OperationsSnapshot::decl(),
        Requester::decl(),
        ApprovalContext::decl(),
        ApprovalBinding::decl(),
        ApprovalState::decl(),
        ApprovalDecision::decl(),
        ApprovalDecisionRequest::decl(),
        ApprovalSnapshot::decl(),
        ApprovalAuditKind::decl(),
        ApprovalAudit::decl(),
        ApprovalsSnapshot::decl(),
    ] {
        types.push_str("export ");
        types.push_str(&declaration);
        types.push('\n');
    }
    let files = [
        ("src/generated/contracts.ts", types),
        (
            "schemas/workspace.schema.json",
            format!(
                "{}\n",
                serde_json::to_string_pretty(&schemars::schema_for!(Manifest)).unwrap()
            ),
        ),
        (
            "schemas/node.schema.json",
            format!(
                "{}\n",
                serde_json::to_string_pretty(&schemars::schema_for!(Node)).unwrap()
            ),
        ),
    ];
    let check = std::env::args().any(|a| a == "--check");
    for (path, content) in files {
        let target = root.join(path);
        if check {
            assert_eq!(
                fs::read_to_string(&target).unwrap(),
                content,
                "generated contract drift: {path}"
            );
        } else {
            fs::create_dir_all(target.parent().unwrap()).unwrap();
            fs::write(target, content).unwrap();
        }
    }
}
