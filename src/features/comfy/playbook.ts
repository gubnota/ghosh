// A recipe is an ordinary Ansible play, not another execution/schema format.
export type Plugin = { name: string; repo: string; commit: string };
export type Model = { url: string; sha256: string; destination: string };
export type ComfyRecipe = { id: string; family: string; root: string; python: string; minDisk: number; plugins: Plugin[]; models: Model[]; requiredNodes: string };
const quote = JSON.stringify;
export function comfyPlaybook(recipe: ComfyRecipe): string {
  if (!/^[a-z][a-z0-9-]{0,55}$/.test(recipe.id)) throw new Error("Use a short lowercase recipe ID.");
  for (const path of [recipe.root, recipe.python]) if (!path.startsWith("/") || /[\n\r\0{}]/.test(path) || path.split("/").includes("..")) throw new Error("Use absolute paths without templates or parent traversal.");
  if (!Number.isFinite(recipe.minDisk) || recipe.minDisk < 1 || recipe.minDisk > 10000) throw new Error("Choose 1–10000 GiB free disk space.");
  const https = (text: string) => { const url = new URL(text); if (url.protocol !== "https:" || url.username || url.password || url.search || url.hash || /[{}\n\r]/.test(text)) throw new Error("Use a public HTTPS URL without credentials, query or template expressions."); };
  const names = new Set<string>();
  for (const plugin of recipe.plugins) {
    if (!/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$/.test(plugin.name) || names.has(plugin.name)) throw new Error("Plugin folder names must be unique simple names.");
    names.add(plugin.name); https(plugin.repo);
    if (!/^[0-9a-f]{40}$/i.test(plugin.commit)) throw new Error("Pin each plugin to its full 40-character Git commit.");
  }
  const destinations = new Set<string>();
  for (const model of recipe.models) {
    https(model.url);
    if (!/^[0-9a-f]{64}$/i.test(model.sha256)) throw new Error("Provide the publisher's SHA-256 for each model.");
    if (!/^(checkpoints|diffusion_models|text_encoders|clip|vae|loras|upscale_models)\/[a-zA-Z0-9_./-]+$/.test(model.destination) || model.destination.split("/").some(p => !p || p === "." || p === "..") || destinations.has(model.destination)) throw new Error("Choose a unique relative model path, e.g. loras/example.safetensors.");
    destinations.add(model.destination);
  }
  if (!recipe.plugins.length && !recipe.models.length) throw new Error("Add at least one plugin or model.");
  const nodes = recipe.requiredNodes.split(",").map(v => v.trim()).filter(Boolean);
  if (nodes.some(v => !/^[a-zA-Z0-9_.:-]{1,150}$/.test(v))) throw new Error("Enter comma-separated ComfyUI node class names.");
  return `# Generated by Ghosh. Edit/run with upstream ansible-playbook as usual.
# Existing ComfyUI installation; never installs CUDA or replaces the base image.
- name: ${quote(`ComfyUI · ${recipe.family}`)}
  hosts: all
  gather_facts: false
  vars:
    comfy_root: ${quote(recipe.root.replace(/\/$/, ""))}
    comfy_python: ${quote(recipe.python)}
    comfy_min_disk_gib: ${recipe.minDisk}
    comfy_plugins: ${quote(recipe.plugins)}
    comfy_models: ${quote(recipe.models)}
    comfy_required_nodes: ${quote(nodes)}
  tasks:
    - name: Inspect existing ComfyUI installation
      ansible.builtin.stat:
        path: '{{ comfy_root }}/main.py'
      register: comfy_main
    - name: Require existing ComfyUI
      ansible.builtin.assert:
        that: comfy_main.stat.isreg | default(false)
        fail_msg: Select the existing ComfyUI directory from your RunPod template.
    - name: Check NVIDIA GPU
      ansible.builtin.command: nvidia-smi --query-gpu=name,memory.total --format=csv,noheader
      changed_when: false
      check_mode: false
    - name: Check disk space and contained plugin/model paths
      ansible.builtin.command:
        argv:
          - '{{ comfy_python }}'
          - -c
          - >-
            import pathlib, shutil, sys;
            r=pathlib.Path(sys.argv[1]).resolve();
            paths=[r/'custom_nodes', r/'models']+[r/'custom_nodes'/n for n in __import__('json').loads(sys.argv[3])]+[r/'models'/n for n in __import__('json').loads(sys.argv[4])];
            assert all(p.resolve().is_relative_to(r) for p in paths), 'Path escapes ComfyUI';
            assert shutil.disk_usage(r).free >= int(sys.argv[2])*1024**3, 'Insufficient free disk';
            print('Paths and disk OK')
          - '{{ comfy_root }}'
          - '{{ comfy_min_disk_gib | string }}'
          - '{{ comfy_plugins | map(attribute="name") | list | to_json }}'
          - '{{ comfy_models | map(attribute="destination") | list | to_json }}'
      changed_when: false
      check_mode: false
    - name: Ensure plugin directory
      ansible.builtin.file:
        path: '{{ comfy_root }}/custom_nodes'
        state: directory
        mode: '0755'
    - name: Install pinned plugin repositories
      ansible.builtin.git:
        repo: '{{ item.repo }}'
        dest: '{{ comfy_root }}/custom_nodes/{{ item.name }}'
        version: '{{ item.commit }}'
        force: false
      loop: '{{ comfy_plugins }}'
      loop_control:
        label: '{{ item.name }}'
    - name: Inspect plugin requirements
      ansible.builtin.stat:
        path: '{{ comfy_root }}/custom_nodes/{{ item.name }}/requirements.txt'
      loop: '{{ comfy_plugins }}'
      register: comfy_requirements
    - name: Install plugin requirements into selected ComfyUI environment
      ansible.builtin.pip:
        requirements: '{{ item.stat.path }}'
        executable: '{{ comfy_python | dirname }}/pip'
      loop: '{{ comfy_requirements.results }}'
      loop_control:
        label: '{{ item.item.name }}'
      when: item.stat.exists and not ansible_check_mode
    - name: Ensure model parent directories
      ansible.builtin.file:
        path: '{{ comfy_root }}/models/{{ item.destination | dirname }}'
        state: directory
        mode: '0755'
      loop: '{{ comfy_models }}'
      loop_control:
        label: '{{ item.destination }}'
    - name: Download and checksum models atomically
      ansible.builtin.get_url:
        url: '{{ item.url }}'
        dest: '{{ comfy_root }}/models/{{ item.destination }}'
        checksum: 'sha256:{{ item.sha256 }}'
        mode: '0644'
        timeout: 120
        unsafe_writes: false
      loop: '{{ comfy_models }}'
      loop_control:
        label: '{{ item.destination }}'
      register: comfy_download
      retries: 3
      delay: 5
      until: comfy_download is succeeded
      when: not ansible_check_mode
    - name: Read running ComfyUI node catalog
      ansible.builtin.uri:
        url: http://127.0.0.1:8188/object_info
        return_content: true
      register: comfy_catalog
      when: comfy_required_nodes | length > 0 and not ansible_check_mode
    - name: Verify required node classes
      ansible.builtin.assert:
        that: comfy_required_nodes | difference(comfy_catalog.json.keys() | list) | length == 0
        fail_msg: Restart ComfyUI using your template's service manager, then rerun verification.
      when: comfy_required_nodes | length > 0 and not ansible_check_mode
    - name: Report follow-up
      ansible.builtin.debug:
        msg: 'Restart ComfyUI using your RunPod template service manager after plugin changes. Check mode skips downloads and pip. Pinned plugin dependencies can still require template-specific CUDA/PyTorch versions.'
`;
}
